package com.inventaria.api.products.infrastructure;

import com.inventaria.api.products.domain.Product;
import com.inventaria.api.products.domain.ProductFilter;
import jakarta.persistence.criteria.JoinType;
import jakarta.persistence.criteria.Predicate;
import org.springframework.data.jpa.domain.Specification;

import java.util.ArrayList;
import java.util.List;

public final class ProductSpecification {

    private ProductSpecification() {}

    public static Specification<Product> withFilter(ProductFilter filter) {
        return (root, query, cb) -> {

            // Eager-fetch associations to avoid N+1 on the list endpoint.
            // Skip on count queries (Long result type) generated by pageable calls.
            if (!Long.class.equals(query.getResultType())) {
                root.fetch("category", JoinType.LEFT);
                root.fetch("supplier", JoinType.LEFT);
                query.distinct(true);
            }

            List<Predicate> predicates = new ArrayList<>();

            if (filter.query() != null && !filter.query().isBlank()) {
                String pattern = "%" + filter.query().toLowerCase() + "%";
                predicates.add(cb.or(
                        cb.like(cb.lower(root.get("name")), pattern),
                        cb.like(cb.lower(root.get("barcode")), pattern)
                ));
            }

            if (filter.categoryId() != null) {
                predicates.add(cb.equal(root.get("category").get("id"), filter.categoryId()));
            }

            if (filter.supplierId() != null) {
                predicates.add(cb.equal(root.get("supplier").get("id"), filter.supplierId()));
            }

            if (filter.type() != null) {
                predicates.add(cb.equal(root.get("type"), filter.type()));
            }

            return cb.and(predicates.toArray(new Predicate[0]));
        };
    }
}
